#!/usr/bin/env python3
"""Generate the C6 read-only DRAFT trial's eight canonical card pairs."""
import argparse
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_prototype import IDS, select_content

ROOT = Path(__file__).resolve().parents[1]


def build_guides(card):
    """Add coaching depth without repeating the main question or action."""
    f = card['facilitator']
    ask = (card['title'] + '\n\nWhat to listen for\n' + '\n\n'.join(f['notice'])
           + '\n\nFollow up\n' + '\n\n'.join(f['follow_ups']))
    move = (card['title'] + '\n\nHow to run it\n' + card['activity']
            + '\n\nWhat to notice\n' + '\n\n'.join(f['try_notice'])
            + '\n\nFollow up\n' + '\n\n'.join(f['try_follow_ups']))
    invitation = f['try_invitation'].strip()
    if invitation.casefold() not in {card['action'].strip().casefold(), card['activity'].strip().casefold()}:
        move += '\n\nSuggested invitation\n' + invitation
    return ask, move


def render(data):
    selected = select_content(data)
    themes = {t['theme_id']: t['label'] for t in selected['themes']}
    lines = ['// Generated by tools/build_v2_content.py. DRAFT review only.',
             '#pragma once', '#include <cstdint>', 'namespace trailguide {',
             'struct Card { const char *id; uint32_t revision; const char *theme; const char *title; const char *ask; const char *action; const char *askGuide; const char *tryGuide; };',
             'static const Card cards[] = {']
    for c in selected['cards']:
        f = c['facilitator']
        ask, move = build_guides(c)
        values = [c['card_id'], c['revision'], themes[c['theme']], c['title'], f['ask'], c['action'], ask, move]
        if any(isinstance(v, str) and not v.isascii() for v in values):
            raise ValueError('Preview font support requires explicit review of non-ASCII copy')
        lines.append('  {' + ', '.join(json.dumps(v) for v in values) + '},')
    lines += ['};', 'static_assert(sizeof(cards) / sizeof(cards[0]) == 8, "Expected eight draft pairs");', '}','']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = render(json.loads((ROOT / 'content/cards.json').read_text()))
    path = ROOT / 'trailguide_v2/cards_generated.h'
    if args.check:
        if not path.exists() or path.read_text() != output:
            parser.exit(1, 'V2 generated content is stale\n')
        print('V2 draft firmware content is current (eight pairs).')
    else:
        path.write_text(output)
        print('Generated eight draft V2 pairs.')

if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""Generate the C6 read-only DRAFT trial's eight canonical card pairs."""
import argparse
import json
import re
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_prototype import IDS, select_content

ROOT = Path(__file__).resolve().parents[1]


def notice_cue(text):
    """Let the heading supply the instruction; preserve the cue and safeguards."""
    original = text.strip()
    cue = re.sub(r'^(?:listen\s+for|look\s+for|notice)\s+', '', original, count=1, flags=re.IGNORECASE)
    if not cue:
        return original
    # Sentence case without damaging names/acronyms such as iOS or AI.
    if cue.split()[0].islower():
        cue = cue[0].upper() + cue[1:]
    return cue


def display_copy(text):
    """Pinned font lacks smart punctuation; retain words, normalize punctuation only."""
    return text.translate(str.maketrans({'’': "'", '“': '"', '”': '"', '—': '--'}))


def build_guides(card):
    """Add coaching depth without repeating the main question or action."""
    f = card['facilitator']
    ask = (card['title'] + '\n\nWhat to listen for\n' + '\n\n'.join(notice_cue(text) for text in f['notice'])
           + '\n\nYou could ask\n' + '\n\n'.join(f['follow_ups']))
    for follow in f.get('conditional_follow_ups', []):
        ask += '\n\n' + follow['when'] + ':\n' + follow['question']
    if f.get('optional_ai_help'):
        ask += '\n\nIf helpful, after listening\n' + f['optional_ai_help']
    move = (card['title'] + '\n\nHow to run it\n' + card['activity']
            + '\n\nWhat to notice\n' + '\n\n'.join(notice_cue(text) for text in f['try_notice'])
            + '\n\nYou could ask\n' + '\n\n'.join(f['try_follow_ups']))
    invitation = f['try_invitation'].strip()
    if invitation.casefold() not in {card['action'].strip().casefold(), card['activity'].strip().casefold()}:
        move += '\n\nIf helpful, offer\n' + invitation
    return display_copy(ask), display_copy(move)


def validate_native_controls(value):
    """LF is deliberate layout; other ASCII controls cannot enter C++ copy.

    Validate before trimming/normalization so rejected bytes cannot disappear.
    Unicode/font review remains the existing, separate rendered-value policy;
    browser JSON is not subject to this native-only restriction.
    """
    if isinstance(value, str):
        if any((ord(c) < 32 and c != '\n') or ord(c) == 127 for c in value):
            raise ValueError('Native copy contains unsupported control character (only LF is allowed)')
    elif isinstance(value, dict):
        for child in value.values():
            validate_native_controls(child)
    elif isinstance(value, list):
        for child in value:
            validate_native_controls(child)


def render(data, ids=IDS):
    selected = select_content(data, ids=ids)
    validate_native_controls(selected)
    themes = {t['theme_id']: t['label'] for t in selected['themes']}
    lines = ['// Generated by tools/build_v2_content.py. DRAFT review only.',
             '#pragma once', '#include <cstdint>', '#include <cstddef>', 'namespace trailguide {',
             'struct Card { const char *id; uint32_t revision; const char *theme; const char *title; const char *ask; const char *action; const char *askGuide; const char *tryGuide; };',
             'static const Card cards[] = {']
    for c in selected['cards']:
        if type(c['revision']) is not int or not 1 <= c['revision'] <= 0xffffffff:
            raise ValueError('Native card revision must be an integer from 1 to 4294967295')
        f = c['facilitator']
        ask, move = build_guides(c)
        values = [display_copy(v) if isinstance(v, str) else v for v in
                  [c['card_id'], c['revision'], themes[c['theme']], c['title'], f['ask'], c['action'], ask, move]]
        if any(isinstance(v, str) and not v.isascii() for v in values):
            raise ValueError('Preview font support requires explicit review of non-ASCII copy')
        lines.append('  {' + ', '.join(json.dumps(v) for v in values) + '},')
    lines += ['};', 'static constexpr std::size_t cardCount = sizeof(cards) / sizeof(cards[0]);',
              f'static_assert(cardCount == {len(selected["cards"])}, "Expected selected draft pairs");', '}','']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = render(json.loads((ROOT / 'content/cards.json').read_text()))
    path = ROOT / 'trailguide_v2/cards_generated.h'
    if args.check:
        if not path.exists() or path.read_text() != output:
            parser.exit(1, 'V2 generated content is stale\n')
        print('V2 draft firmware content is current (eight pairs).')
    else:
        path.write_text(output)
        print('Generated eight draft V2 pairs.')

if __name__ == '__main__':
    main()

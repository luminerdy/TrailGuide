#!/usr/bin/env python3
"""Resolve the canonical reusable coaching layer to pinned-font C++ (DRAFT)."""
import argparse,json
from pathlib import Path
from build_compass_coaching import validate,PATHS
ROOT=Path(__file__).resolve().parents[1]
# Pinned Montserrat fonts cover printable ASCII; preserve meaning, normalize only
# typographic punctuation. Unexpected glyphs fail rather than disappear on device.
PUNCT=str.maketrans({'’':"'",'‘':"'",'“':'"','”':'"','–':'-','—':' - ','…':'...','\u00a0':' '})
def native(text):
    text=text.translate(PUNCT)
    if any(ord(c)>126 or (ord(c)<32 and c!='\n') for c in text):raise ValueError('Unsupported native font glyph: '+repr(text))
    return json.dumps(text,ensure_ascii=True)
def render(layer,catalog):
    content=validate(layer,catalog)
    rows=[]
    for e in content['entries']:
        rows.append(' {'+','.join([native(e['id']),native(e['type']),str(PATHS.index(e['path']) if 'path' in e else -1),native(e['text']),native(e.get('guidance',''))])+'},')
    return '\n'.join(['// Generated by tools/build_v3_coaching.py; canonical DRAFT, do not edit.','#pragma once','#include <stddef.h>','namespace trailguide_coaching {','struct Entry { const char *id,*type; int path; const char *text,*guidance; };','static constexpr const char *pathLabels[]={'+','.join(native(p['label']) for p in content['paths'])+'};','static constexpr Entry entries[]={',*rows,'};','static constexpr size_t entryCount=sizeof(entries)/sizeof(entries[0]);','}','',''])
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--content',type=Path,default=ROOT/'content/coaching.json');p.add_argument('--cards',type=Path,default=ROOT/'content/cards.json');p.add_argument('--output',type=Path,default=ROOT/'trailguide_v3/coaching_generated.h');p.add_argument('--check',action='store_true');a=p.parse_args()
    text=render(json.loads(a.content.read_text()),json.loads(a.cards.read_text()))
    if a.check:
        if not a.output.exists() or a.output.read_text()!=text:p.exit(1,'Native coaching header stale\n')
        print('PASS canonical native coaching header current')
    else:a.output.write_text(text)
if __name__=='__main__':main()
